// EXTRA-4: the workflow's commit step fails when every push attempt fails
// ---------------------------------------------------------------------------

function commitStepScript(): string {
  return stepScript('Commit refreshed data');
}

function stepScript(name: string): string {
  const yml = readFileSync(new URL('../.github/workflows/refresh.yml', import.meta.url), 'utf8');
  const lines = yml.split('\n');
  const start = lines.findIndex((l) => l.trim() === `- name: ${name}`);
  assert.ok(start >= 0, `step "${name}" present`);
  const runIdx = lines.findIndex((l, i) => i > start && /^\s+run: \|\s*$/.test(l));
  const indent = (l: string) => l.match(/^ */)![0].length;
  const body: string[] = [];
  const bodyIndent = indent(lines[runIdx + 1]);
  for (let i = runIdx + 1; i < lines.length; i++) {
    if (lines[i].trim() && indent(lines[i]) < bodyIndent) break;
    body.push(lines[i].slice(bodyIndent));
  }
  return body.join('\n');
}

function runCommitStep(git: { diffQuiet: boolean; pushSucceedsOnAttempt: number | null }): { status: number | null; out: string; pushes: number } {
  const dir = mkdtempSync(join(tmpdir(), 'zbt-push-'));
  try {
    const counter = join(dir, 'pushes');
    writeFileSync(counter, '0');
    // Stub git on PATH: no repository, credentials or remote is touched.
    const stub = `#!/bin/bash
case "$1" in
  config|add|commit) exit 0 ;;
  diff) exit ${git.diffQuiet ? 0 : 1} ;;
  push) n=$(( $(cat "${counter}") + 1 )); echo $n > "${counter}"; echo "SIMULATED_PUSH attempt $n"; ${git.pushSucceedsOnAttempt === null ? 'exit 1' : `[ $n -ge ${git.pushSucceedsOnAttempt} ] && exit 0 || exit 1`} ;;
  pull) echo SIMULATED_PULL; exit 0 ;;
esac
exit 2
`;
    writeFileSync(join(dir, 'git'), stub);
    chmodSync(join(dir, 'git'), 0o755);
    // GitHub Actions runs `run:` blocks with bash -e (and -o pipefail for shell: bash).
    const res = spawnSync('bash', ['--noprofile', '--norc', '-eo', 'pipefail', '-c', commitStepScript()], { env: { PATH: `${dir}:${process.env.PATH}`, GITHUB_EVENT_NAME: 'audit', GITHUB_RUN_ID: '0' }, encoding: 'utf8' });
    return { status: res.status, out: `${res.stdout}${res.stderr}`, pushes: Number(readFileSync(counter, 'utf8')) };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('EXTRA-3: the workflow fails visibly with the recorded reason (derivation failure, failed sources, or no record)', () => {
  const yml = readFileSync(new URL('../.github/workflows/refresh.yml', import.meta.url), 'utf8');
  const step = yml.slice(yml.indexOf('- name: Report refresh failure'));
  assert.match(step.split('\n')[1], /^\s+if: always\(\) && steps\.refresh\.outcome == 'failure'\s*$/, 'reported even when a later step (e.g. Build site) failed too');
  const script = stepScript('Report refresh failure');
  const runIn = (status: unknown | null) => {
    const dir = mkdtempSync(join(tmpdir(), 'zbt-report-'));
    try {
      if (status !== null) {
        mkdirSync(join(dir, 'data'));
        writeFileSync(join(dir, 'data', 'status.json'), JSON.stringify(status));
      }
      const res = spawnSync('bash', ['--noprofile', '--norc', '-eo', 'pipefail', '-c', script], { cwd: dir, env: { PATH: process.env.PATH }, encoding: 'utf8' });
      return { status: res.status, out: `${res.stdout}${res.stderr}` };
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  };
  const derive = runIn({ lastRun: { id: 'abc123', startedAt: NOW, outcome: 'failed', sources: { alpha: 'ok', derive: 'failed' }, derive: { outcome: 'failed', error: 'Error: boom\nsecond line' } }, sources: {} });
  assert.equal(derive.status, 1);
  assert.match(derive.out, /^::error::Refresh failed \(last recorded run abc123 started 2026-10-08T20:00:00Z: derivation failed: Error: boom second line\)\. The published site keeps the previously derived data/m);
  const sources = runIn({ lastRun: { id: 'def456', startedAt: NOW, outcome: 'failed', sources: { alpha: 'failed', beta: 'skipped', gamma: 'ok' }, derive: { outcome: 'ok', error: null } }, sources: {} });
  assert.equal(sources.status, 1);
  assert.match(sources.out, /outcome failed; sources not ok: alpha=failed, beta=skipped\)/);
  const none = runIn(null);
  assert.equal(none.status, 1);
  assert.match(none.out, /::error::Refresh failed \(no run record was written\)/);
});

test('EXTRA-4: exhausted push retries fail the commit step; a later successful push and a no-change run succeed', () => {
  const failed = runCommitStep({ diffQuiet: false, pushSucceedsOnAttempt: null });
  assert.notEqual(failed.status, 0, `all pushes failed but the step succeeded:\n${failed.out}`);
  assert.equal(failed.pushes, 3);
  assert.match(failed.out, /::error::Could not push refreshed data after 3 attempts/);

  const retried = runCommitStep({ diffQuiet: false, pushSucceedsOnAttempt: 2 });
  assert.equal(retried.status, 0, retried.out);
  assert.equal(retried.pushes, 2);

  const unchanged = runCommitStep({ diffQuiet: true, pushSucceedsOnAttempt: null });
  assert.equal(unchanged.status, 0, unchanged.out);
  assert.equal(unchanged.pushes, 0);
});
