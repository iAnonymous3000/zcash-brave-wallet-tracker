/** Raw-file server: path -> content (per ref when given as "ref:path"), anything else 404. */
function rawHttp(files: Record<string, string | ((ref: string) => string | null)>, log: string[] = []): Http {
  return new Http({
    sleep: async () => {},
    maxRetries: 0,
    fetch: (async (input: string | URL | Request) => {
      const url = String(input);
      log.push(url);
      const m = url.match(/^https:\/\/raw\.githubusercontent\.com\/brave\/brave-core\/([^/]+)\/(.+)$/);
      if (!m) return new Response('not found', { status: 404 });
      const ref = decodeURIComponent(m[1]);
      const f = files[m[2]];
      const body = typeof f === 'function' ? f(ref) : f;
      return body === undefined || body === null ? new Response('not found', { status: 404 }) : new Response(body);
    }) as typeof fetch,
  });
}

function ctxFor(http: Http, commitSha: () => Promise<string | null>, get: (id: string) => SourceEnvelope<unknown> | null = () => null): Ctx {
  return { now: NOW, trigger: 'test', log: quiet, http, gh: { commitSha: async () => commitSha() } as unknown as Ctx['gh'], get: get as Ctx['get'] };
}

function pkg(name: string, version: string, opts: { source?: string | null; deps?: string[]; multiline?: boolean } = {}): string {
  const src = opts.source === undefined ? CRATES_IO : opts.source;
  const lines = ['[[package]]', `name = "${name}"`, `version = "${version}"`];
  if (src) lines.push(`source = "${src}"`);
  if (opts.deps?.length) {
    if (opts.multiline === false) lines.push(`dependencies = [${opts.deps.map((d) => `"${d}"`).join(', ')}]`);
    else lines.push('dependencies = [', ...opts.deps.map((d) => ` "${d}",`), ']');
  }
  return lines.join('\n');
}
const lockOf = (...pkgs: string[]) => `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n${pkgs.join('\n\n')}\n`;
const ZCASH_TOML = '[package]\nname = "zcash"\nversion = "1.0.0"\n\n[dependencies]\norchard = { version = "0.13", default-features = false }\n';
