async function depsAt(lock: string, extra: Record<string, string> = {}): Promise<{ snap: BraveDepsSnapshot; result: Awaited<ReturnType<typeof braveDeps.collect>> }> {
  const http = rawHttp({ [LOCKFILE]: lock, [CARGO]: ZCASH_TOML, DEPS: FORK_DEPS, [NETWORK]: '"https://zcash.wallet.brave.com/"', [RPC]: '"/cash.z.wallet.sdk.rpc.CompactTxStreamer/GetLightdInfo"', ...extra });
  const result = await braveDeps.collect(ctxFor(http, async () => SHA_A, (id) => (id === 'brave-releases' ? releasesWith('v1.2.3') : null)), null);
  return { snap: result.data.snapshots['v1.2.3'], result };
}

