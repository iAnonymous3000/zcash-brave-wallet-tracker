/** Raw-file server for brave-core: path -> content (or per-ref function), anything else 404. */
function rawHttp(files: Record<string, string | null | ((ref: string) => string | null)>, log: string[] = []): Http {
  return new Http({
    sleep: async () => {},
    maxRetries: 0,
    fetch: (async (input: string | URL | Request) => {
      const url = String(input);
      log.push(url);
      const m = url.match(/^https:\/\/raw\.githubusercontent\.com\/brave\/brave-core\/([^/]+)\/(.+)$/);
      if (!m) return new Response('not found', { status: 404 });
      const f = files[m[2]];
      const body = typeof f === 'function' ? f(decodeURIComponent(m[1])) : f;
      return body === undefined || body === null ? new Response('not found', { status: 404 }) : new Response(body);
    }) as typeof fetch,
  });
}

function ctxFor(http: Http, commitSha: () => Promise<string | null>, get: (id: string) => SourceEnvelope<unknown> | null = () => null, now = NOW): Ctx {
  return { now, trigger: 'test', log: quiet, http, gh: { commitSha: async () => commitSha() } as unknown as Ctx['gh'], get: get as Ctx['get'] };
}

function pkg(name: string, version: string, opts: { source?: string | null; deps?: string[] } = {}): string {
  const src = opts.source === undefined ? CRATES_IO : opts.source;
  const lines = ['[[package]]', `name = "${name}"`, `version = "${version}"`];
  if (src) lines.push(`source = "${src}"`);
  if (opts.deps?.length) lines.push('dependencies = [', ...opts.deps.map((d) => ` "${d}",`), ']');
  return lines.join('\n');
}
