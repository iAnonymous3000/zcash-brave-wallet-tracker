interface Step { run: string; env: Record<string, string>; ifLine: string | null }

/** A step of refresh.yml: its run script (block or single line), env mapping and if: condition. */
function workflowStep(name: string): Step {
  const lines = readFileSync(new URL('../.github/workflows/refresh.yml', import.meta.url), 'utf8').split('\n');
  const start = lines.findIndex((l) => l.trim() === `- name: ${name}`);
  assert.ok(start >= 0, `step "${name}" present`);
  const indent = (l: string) => l.match(/^ */)![0].length;
  const keyIndent = indent(lines[start]) + 2;
  let end = lines.findIndex((l, i) => i > start && l.trim() && indent(l) < keyIndent);
  if (end === -1) end = lines.length;
  const body = lines.slice(start + 1, end);
  const out: Step = { run: '', env: {}, ifLine: null };
  for (let i = 0; i < body.length; i++) {
    const l = body[i];
    if (indent(l) !== keyIndent) continue;
    const m = l.trim().match(/^([\w-]+):\s*(.*)$/);
    if (!m) continue;
    const block = () => {
      const rows: string[] = [];
      for (let j = i + 1; j < body.length && (!body[j].trim() || indent(body[j]) > keyIndent); j++) rows.push(body[j]);
      return rows;
    };
    if (m[1] === 'if') out.ifLine = m[2];
    if (m[1] === 'env') for (const row of block()) { const kv = row.trim().match(/^(\w+):\s*(.*)$/); if (kv) out.env[kv[1]] = kv[2]; }
    if (m[1] === 'run') {
      if (m[2] !== '|') out.run = m[2];
      else {
        const rows = block();
        const bodyIndent = Math.min(...rows.filter((r) => r.trim()).map(indent));
        out.run = rows.map((r) => r.slice(bodyIndent)).join('\n');
      }
    }
  }
  return out;
}

const parseOutputs = (file: string): Record<string, string> => {
  if (!existsSync(file)) return {};
  return Object.fromEntries(readFileSync(file, 'utf8').split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
};

/** Resolve `${{ steps.refresh.outputs.X }}` expressions of a step's env against the refresh step's outputs. */
function resolveEnv(step: Step, outputs: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(step.env)) {
    if (/secrets\.|github\./.test(v)) continue;
    out[k] = v.replace(/\$\{\{\s*steps\.refresh\.outputs\.([\w-]+)\s*\}\}/g, (_, name) => outputs[name] ?? '');
  }
  return out;
}

/** Run the "Refresh sources" step with `node` replaced by `nodeStub` (a bash body), then the report step on its outputs. */
function simulate(root: string, nodeStub: string, extraEnv: Record<string, string> = {}): { refresh: { status: number | null; out: string }; outputs: Record<string, string>; report: { status: number | null; out: string } } {
  const bin = join(root, 'bin');
  mkdirSync(bin, { recursive: true });
  writeFileSync(join(bin, 'node'), `#!/bin/bash\n${nodeStub}\n`);
  chmodSync(join(bin, 'node'), 0o755);
  const outFile = join(root, 'github_output');
  rmSync(outFile, { force: true });
  const refreshStep = workflowStep('Refresh sources');
  // GitHub Actions runs `run:` blocks with bash -e (and -o pipefail for shell: bash).
  const r = spawnSync('bash', ['--noprofile', '--norc', '-eo', 'pipefail', '-c', refreshStep.run], { cwd: root, env: { PATH: `${bin}:${process.env.PATH}`, GITHUB_OUTPUT: outFile, ...extraEnv }, encoding: 'utf8' });
  const outputs = parseOutputs(outFile);
  const reportStep = workflowStep('Report refresh failure');
  const rep = spawnSync('bash', ['--noprofile', '--norc', '-eo', 'pipefail', '-c', reportStep.run], { cwd: root, env: { PATH: process.env.PATH, ...resolveEnv(reportStep, outputs) }, encoding: 'utf8' });
  return { refresh: { status: r.status, out: `${r.stdout}${r.stderr}` }, outputs, report: { status: rep.status, out: `${rep.stdout}${rep.stderr}` } };
}

