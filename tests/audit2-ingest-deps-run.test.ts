test('R-STATUS: "failed" means the envelope is untouched; staleSince is kept by a failure, absent within the window, cleared by a complete run', async () => {
  await withDataDir(async (dir) => {
    const base = { trigger: 'test', token: null, log: quiet };
    const status = () => readData(dir, 'status.json').sources.src;
    await run.runRefresh({ ...base, now: '2026-10-08T08:00:00Z', collectors: [scripted('src', () => ({ data: { v: 1 } }))] });
    // Within the window: partial, not stale.
    await run.runRefresh({ ...base, now: '2026-10-08T12:00:00Z', collectors: [scripted('src', () => ({ data: { v: 2 }, partial: true, staleSince: '2026-10-08T08:00:00Z' }))] });
    assert.equal(status().lastOutcome, 'partial');
    assert.equal(status().staleSince, undefined);
    // Beyond it: stale.
    await run.runRefresh({ ...base, now: '2026-10-08T15:00:00Z', collectors: [scripted('src', () => ({ data: { v: 3 }, partial: true, staleSince: '2026-10-08T08:00:00Z' }))] });
    assert.equal(status().lastOutcome, 'partial');
    assert.equal(status().staleSince, '2026-10-08T08:00:00Z');
    assert.match(status().limitations[0], /^stale: some values this source should refresh every run could not be refreshed since 2026-10-08T08:00:00Z \(7 h,/);
    // A collector that throws stores nothing: failed, envelope byte for byte unchanged, still stale since 08:00.
    const before = readFileSync(join(dir, 'sources', 'src.json'));
    const r = await run.runRefresh({ ...base, now: '2026-10-08T17:00:00Z', collectors: [scripted('src', () => { throw new Error('HTTP 503'); })] });
    assert.equal(r.sources.src, 'failed');
    assert.deepEqual(readFileSync(join(dir, 'sources', 'src.json')), before);
    assert.equal(status().lastOutcome, 'failed');
    assert.equal(status().lastError, 'Error: HTTP 503');
    assert.equal(status().staleSince, '2026-10-08T08:00:00Z');
    // A complete run clears it.
    await run.runRefresh({ ...base, now: '2026-10-08T19:00:00Z', collectors: [scripted('src', () => ({ data: { v: 4 } }))] });
    assert.equal(status().lastOutcome, 'ok');
    assert.equal(status().staleSince, undefined);
    assert.equal(status().lastCompleteAt, '2026-10-08T19:00:00Z');
  });
});

