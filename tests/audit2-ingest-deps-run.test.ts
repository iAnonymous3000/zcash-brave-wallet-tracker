test('R-DEPS-LOCK: several linked versions: lock is the highest, all stay candidates, and exposure still sees the lower one', async () => {
  // zcash -> orchard 0.13.0 directly and -> zcash_primitives -> orchard 0.15.0 transitively (not "direct wins").
  const lock = lockOf(
    pkg('zcash', '1.0.0', { source: null, deps: ['orchard 0.13.0', 'zcash_primitives'] }),
    pkg('orchard', '0.13.0'),
    pkg('orchard', '0.15.0'),
    pkg('zcash_primitives', '0.29.0', { source: null, deps: ['orchard 0.15.0'] }),
  );
  const { snap, result } = await collectTag(lock);
  assert.deepEqual(snap.lock.orchard, { version: '0.15.0', source: 'crates.io' }, 'Brave resolves orchard 0.15.0 (the highest linked), not the lowest');
  assert.deepEqual(snap.resolution?.candidates.orchard.map((c) => [c.version, c.reachable, c.direct]), [['0.13.0', true, true], ['0.15.0', true, false]]);
  assert.deepEqual(snap.resolution?.multiple, ['orchard']);
  assert.ok(result.limitations?.some((l) => /links 2 versions of orchard \(0\.13\.0 \(direct\), 0\.15\.0\).*"lock" lists 0\.15\.0, the highest/.test(l)), 'the note names the highest');
  assert.equal(exposed(snap, 'orchard', '< 0.14.0'), true, 'the lower linked version is still exposure');
  assert.equal(exposed(snap, 'orchard', '>= 0.16.0'), false);
});

