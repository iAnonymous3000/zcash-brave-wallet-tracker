    if (url === `https://raw.githubusercontent.com/brave/gate3/${SHA_A}/app/api/swap/constants.py`) return new Response(GATE3);
    // Outage: brave-variations unreachable.
    if (url === 'https://api.github.com/repos/brave/brave-variations/commits/main') return outage ? new Response('{"message":"Server Error"}', { status: 502 }) : new Response(SHA_B);
    if (url === `https://api.github.com/repos/brave/brave-variations/contents/studies?ref=${SHA_B}`) return json([{ name: 'ZCashStudy.json5', type: 'file', sha: blobSha(STUDY) }]);
    if (url === `https://raw.githubusercontent.com/brave/brave-variations/${SHA_B}/studies/ZCashStudy.json5`) return new Response(STUDY);
    if (url === `https://raw.githubusercontent.com/brave/brave-core/master/${LOCKFILE}`) return new Response(lockOf(pkg('zcash', '1.0.0', { source: null, deps: ['orchard'] }), pkg('orchard', '0.15.0')));
